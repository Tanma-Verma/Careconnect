"""Real HTTP smoke test. No fake providers; requires a configured running backend."""
import argparse
import json
import secrets
import sys
from pathlib import Path
from uuid import uuid4
from urllib.parse import urlparse

import httpx


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--base-url", default="http://localhost:3000")
    parser.add_argument("--origin", default="http://localhost:3000")
    parser.add_argument("--report", type=Path, help="Existing synthetic PDF/TXT fixture to ingest")
    args = parser.parse_args()
    base = args.base_url.rstrip("/")
    with httpx.Client(base_url=base, headers={"Origin": args.origin, "Host": urlparse(args.origin).netloc, "X-Requested-With": "CareConnect"}, timeout=240) as client:
        health = client.get("/health")
        health.raise_for_status()
        configured = health.json()["providers"]
        if not configured["embeddings_configured"] or not configured["llm_configured"]:
            print("NOT VERIFIED: configure EMBEDDING_API_BASE_URL/API_KEY/MODEL and LLM_API_BASE_URL/API_KEY/MODEL, then recreate backend.")
            return 2
        # Explicit synthetic input; no records are generated by application API responses.
        report = (
            "SYNTHETIC HACKATHON REPORT — NOT A REAL PATIENT\n"
            "Patient: Demo Alpha. Visit date: 1 November 2026.\n"
            "Blood pressure measured at this visit: 122/80 mmHg. Pulse: 72 beats per minute.\n"
            "The report recommends discussing results at a follow-up visit in two weeks.\n"
        ).encode()
        filename = "synthetic-live-report.txt"
        if args.report:
            report = args.report.read_bytes()
            filename = args.report.name
        response = client.post("/api/v1/auth/register", json={"email": f"live-{uuid4().hex}@example.test", "password": secrets.token_urlsafe(24), "role": "PATIENT"})
        response.raise_for_status()
        client.headers["X-CSRF-Token"] = response.json()["csrf_token"]
        media_type = "application/pdf" if filename.lower().endswith(".pdf") else "text/plain"
        ingestion = client.post("/api/v1/documents", files={"file": (filename, report, media_type)})
        if ingestion.status_code != 200:
            print("NOT VERIFIED: document ingestion failed:", ingestion.json().get("error", "Check backend diagnostics."))
            return 3
        document = ingestion.json()["document"]
        assert document["state"] == "READY"
        print("INGESTION_SUCCESS:", document["filename"], "READY", "document_id=" + document["id"])
        result = client.post("/api/v1/ai/chat", json={"message": "What blood pressure was measured at my visit? Give the exact documented value and units."})
        if result.status_code != 200:
            print("NOT VERIFIED: generation failed:", result.json().get("error", "Check backend diagnostics."))
            return 4
        answer = result.json()
        if "122/80" not in answer["answer"] or not answer["citations"]:
            print("NOT VERIFIED: model did not return the expected grounded fact and citations.")
            return 5
        for citation in answer["citations"]:
            assert citation["document_id"] == document["id"]
            source = client.get(citation["url"].split("#")[0])
            source.raise_for_status()
            assert source.content == report
        print(json.dumps({"live_embeddings_verified": True, "live_llm_verified": True,
                          "document_id": document["id"], "request_id": answer["request_id"],
                          "answer": answer["answer"], "citations": answer["citations"]}, indent=2))
        client.post("/api/v1/auth/logout").raise_for_status()
    return 0


if __name__ == "__main__":
    sys.exit(main())
